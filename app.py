def get_prefill(pooled: str) -> S.Prefill:
    cache = st.session_state.prefills
    if pooled not in cache:
        cache[pooled] = S.prefill(pooled, ins)
    return cache[pooled]


if model_composites:
    with st.expander(f"Combined variables found in '{S.COMPOSITE_SHEET}' "
                     f"({len(model_composites)})"):
        table = []
        for v in model_composites:
            pf = get_prefill(v)
            table.append({
                "Variable": v,
                "Formula": ins.composites[v]["formula"],
                "Pre-fill": {"composite": f"{len(pf.rows)} campaigns",
                             "sum-match": f"{len(pf.rows)} campaigns (by sum)",
                             "none": "fill in by hand"}[pf.source],
            })
        st.dataframe(pd.DataFrame(table), hide_index=True,
                     width="stretch")

options = model_composites + [v for v in ins.variables if v not in ins.composites]
selected = st.multiselect(
    "Combined variables to split", options, key=f"sel::{file_key}",
    format_func=lambda v: f"{v}  (composite)" if v in ins.composites else v,
    help="Composites from the model file are listed first and pre-filled. "
         "A variable combined outside the platform is pre-filled when a set "
         "of its channel's DATA columns sums exactly to it.")

splits: list[Split] = []
curve_modes, smoothing, acc_transform, acc_raw, rescale = {}, {}, {}, {}, {}
problems: list[str] = []

for pooled in selected:
    pf = get_prefill(pooled)
    ek = f"{file_key}::{pooled}"
    with st.container(border=True):
        st.subheader(pooled)
        st.caption({
            "composite": f"Pre-filled from the formula `{pf.formula}`.",
            "sum-match": "Pre-filled: these DATA columns sum exactly to the "
                         "pooled variable's Raw series.",
            "none": "Nothing to pre-fill from. Add one row per campaign.",
        }[pf.source])
        for n in pf.notes:
            st.info(n)

        rows = [{k: (v or None) for k, v in r.items()} for r in pf.rows] \
            or [{"name": None, "raw": None, "spend": None}] * 2
        channel = S.split_name(pooled)[0]
        likely_raw = S.likely_columns(ins.data_cols, pooled)
        likely_spend = [c for c in ins.data_cols if S.split_name(c)[0] == channel
                        and S.split_name(c)[1] in S.SPEND_TOKENS]
        edited = st.data_editor(
            pd.DataFrame(rows, columns=["name", "raw", "spend"]),
            key=f"ed::{ek}", num_rows="dynamic", hide_index=True,
            width="stretch",
            column_config={
                "name": st.column_config.TextColumn(
                    "New variable name",
                    help="Leave blank to use the metric column's name."),
                "raw": st.column_config.SelectboxColumn(
                    "Column with the modelled metric",
                    options=ranked(ins.data_cols, likely_raw),
                    help="The impressions, clicks or GRPs the model was built on."),
                "spend": st.column_config.SelectboxColumn(
                    "Column with spend",
                    options=ranked(ins.data_cols, likely_spend)),
            })

        camps, bad = [], []
        for i, row in edited.reset_index(drop=True).iterrows():
            nm, raw, sp = _s(row["name"]), _s(row["raw"]), _s(row["spend"])
            if not (nm or raw or sp):
                continue                                   # empty row
            if not raw or not sp:
                bad.append(f"row {i + 1} needs both a metric and a spend column")
                continue
            camps.append(Campaign(nm or raw, raw, sp))
        names = [c.name for c in camps]
        if len(camps) < 2:
            bad.append("at least two campaigns are needed")
        if len(set(names)) != len(names):
            bad.append("two campaigns have the same name")
        if pooled in names:
            bad.append("a campaign has the pooled variable's own name")
        raws = [c.raw for c in camps]
        if len(set(raws)) != len(raws):
            bad.append("the same metric column is used twice")
        problems += [f"**{pooled}**: {b}" for b in bad]

        on_spend = [c.raw == c.spend for c in camps]
        a, b = st.columns([3, 2])
        mode_opts = list(CURVE_LABELS)
        default_mode = ("additive" if (camps and all(on_spend)
                                       and DEFAULT_CURVE == "shared_shape")
                        else DEFAULT_CURVE)
        mode = a.radio("Response curves", mode_opts, horizontal=True,
                       index=mode_opts.index(default_mode), key=f"cm::{ek}",
                       format_func=CURVE_LABELS.get)
        if camps and all(on_spend) and mode == "shared_shape":
            a.warning("Metric and spend are the same columns, so this variable "
                      "was modelled on spend. Same-shape curves would come out "
                      "identical -- use 'Scaled by volume'.")
        elif any(on_spend) and not all(on_spend):
            a.warning("Some rows use the spend column as the metric and some "
                      "do not. The pooled variable has one unit, so one of "
                      "these is probably the wrong column.")
        curve_modes[pooled] = mode

        sm0 = pf.smoothing or {}
        win = b.number_input("Smoothing before modelling (days, 1 = none)",
                             1, 90, int(sm0.get("window", 1)), key=f"sw::{ek}",
                             help="Pre-filled when the composite formula is "
                                  "a bma/cma average.")
        cen = b.checkbox("Centred", value=bool(sm0.get("centred", False)),
                         key=f"sc::{ek}")
        if win > 1:
            smoothing[pooled] = {"window": int(win), "centred": bool(cen)}

        with st.expander("Diagnose this variable"):
            st.caption("For when the checks stop on this variable. Each one "
                       "reads both files and writes nothing.")
            d1, d2 = st.columns(2)
            which = None
            if d1.button("Which columns are missing?", key=f"dsum::{ek}",
                         disabled=len(camps) < 1,
                         help="When the campaigns do not add up to the "
                              "combined variable: finds DATA columns that "
                              "would account for the gap."):
                which = "sum"
            if d2.button("Was it smoothed before modelling?", key=f"dsm::{ek}",
                         disabled=len(camps) < 1,
                         help="When the totals match but individual days do "
                              "not: tests rolling averages of the campaigns."):
                which = "smoothing"
            if which:
                with st.spinner("Diagnosing..."):
                    st.session_state[f"diag::{ek}"] = S.diagnose(
                        files, {"SPLITS": [Split(pooled=pooled, campaigns=camps)]},
                        which, pooled)
            dres = st.session_state.get(f"diag::{ek}")
            if dres is not None:
                st.code((dres.output or "") + (dres.crash or ""), language="text")

        with st.expander("Overrides -- only once a diagnosis shows it is safe"):
            st.caption("Each one is a recorded decision, not a switch: the "
                       "reason is printed in the run output, and the tool "
                       "still measures whether it holds and refuses if not.")
            for store, label, hint in (
                (acc_transform, "Accept a failed transform check",
                 "e.g. scores 0.98 for reasons unrelated to decay; campaign "
                 "shares move 0.003pp"),
                (rescale, "Treat the pooled figure as authoritative on "
                          "hand-adjusted days",
                 "e.g. 5 days in June replaced with a typed average"),
                (acc_raw, "Accept that the pooled Raw is wrong and the "
                          "campaign columns are right",
                 "e.g. Raw wrongly includes one component (0.38%), confirmed "
                 "with the modeller"),
            ):
                reason = st.text_input(f"{label} — reason", key=f"{label}::{ek}",
                                       placeholder=hint).strip()
                if reason:
                    store[pooled] = reason

    if camps:
        splits.append(Split(pooled=pooled, campaigns=camps))

