PASS_ICON, FAIL_ICON, WARN_ICON = "✅", "❌", "⚠️"
CURVE_LABELS = {
    "own_curve": "Own curve per campaign (built from the model)",
    "shared_shape": "Same shape, differing by cost",
    "additive": "Scaled by volume (sums to the pooled curve)",
}
