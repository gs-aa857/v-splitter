# ---------------------------------------------------------------- helpers ---

def _s(v) -> str:
    """A data_editor cell as a clean string (cells can be None or NaN)."""
    if v is None or (isinstance(v, float) and v != v):
        return ""
    return str(v).strip()


def _digest(*parts) -> str:
    return hashlib.sha1(repr(parts).encode()).hexdigest()[:12]


def _file_id(f) -> str:
    return getattr(f, "file_id", None) or hashlib.sha1(f.getvalue()).hexdigest()


def ranked(cols: list[str], first: list[str]) -> list[str]:
    """Likely columns first, then the rest. Never a filtered list: the import
    file may name a channel differently from the model."""
    return first + [c for c in cols if c not in first]


def summarise(text: str) -> list[tuple[str, str]]:
    rows = []
    for line in text.splitlines():
        s = line.strip()
        if s.startswith("Transform check PASSED"):
            rows.append((PASS_ICON, s))
        elif s.startswith(("Transform check FAILED", "STOPPED")):
            rows.append((FAIL_ICON, s))
        elif s.startswith(("contribution ", "spend ", "raw ")) and "->" in s:
            before, after = s.split("->", 1)
            a = re.findall(r"[\d,]+\.?\d*", before)
            b = re.findall(r"[\d,]+\.?\d*", after)
            ok = a and b and a[-1] == b[0]
            rows.append((PASS_ICON if ok else FAIL_ICON, s))
        elif s.startswith(("WARNING", "NOTE", "NO CURVE", "ACCEPTED",
                           "RESCALED", "RAW MISMATCH")):
            rows.append((WARN_ICON, s))
        elif s.startswith(("All checks passed", "Written:")):
            rows.append((PASS_ICON, s))
    return rows


def config_text(settings: dict) -> str:
    out = ["# Generated by the MMM variable splitter app. Keep this alongside",
           "# the result file as a record of exactly how it was split, or",
           "# give it to whoever maintains the tool to repeat the run exactly.",
           ""]
    for k in ("DECAY_IS_RETENTION", "CURVE_MODE", "ACCEPT_TRANSFORM_MISMATCH",
              "ACCEPT_RAW_MISMATCH", "SMOOTHING", "RESCALE_TO_POOLED"):
        out.append(f"{k} = {settings.get(k, S.CONFIG_DEFAULTS[k])!r}")
    out += ["", "SPLITS = ["]
    for sp in settings["SPLITS"]:
        out += ["    Split(", f"        pooled={sp.pooled!r},", "        campaigns=["]
        out += [f"            Campaign({c.name!r}, {c.raw!r}, {c.spend!r}),"
                for c in sp.campaigns]
        out += ["        ],", "    ),"]
    out.append("]")
    return "\n".join(out)


def show_run(r: S.RunResult, ok_text: str) -> None:
    if r.crash:
        st.error("The tool hit an unexpected error. This is a fault in the "
                 "tool, not a finding about your files. Send the message "
                 "below to whoever maintains it.")
        st.code(r.crash, language="text")
    elif r.code == 0:
        st.success(ok_text)
    else:
        st.error("Stopped. Nothing was written -- see below for what was found.")
    rows = summarise(r.output)
    if rows:
        st.subheader("What it found")
        for icon, line in rows:
            st.markdown(f"{icon} &nbsp; `{line}`", unsafe_allow_html=True)
    with st.expander("Full output", expanded=(r.code != 0 and not r.crash)):
        st.code(r.output or "(no output)", language="text")


